from pathlib import Path
import sys
from collections import defaultdict

import pandas as pd
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import (
    TRAIN_SOURCE1,
    TRAIN_SOURCE2,
    TRAIN_SOURCE3,
    DEFAULT_CHUNK_SIZE,
)
from src.blocking import generate_blocking_keys


SAMPLE_SIZE = 20_000
RANDOM_STATE = 42

STRATEGIES = {
    "name_prefix + house_number": [
        "name_prefix",
        "house_number",
    ],
    "ALL THREE": [
        "name_prefix",
        "address_prefix",
        "house_number",
    ],
}


def load_s1_sample():
    df = pd.read_csv(
        TRAIN_SOURCE1,
        sep="\t",
        dtype=str,
        keep_default_na=False,
        usecols=[
            "entity_id",
            "business_name",
            "business_address",
            "country",
        ],
    )

    sample = df.sample(
        n=min(SAMPLE_SIZE, len(df)),
        random_state=RANDOM_STATE,
    ).copy()

    return sample


def build_candidate_indexes(source_path):
    """
    Build blocking indexes for one source.

    key -> number of records having that key

    We only need counts here, not the actual IDs.
    """

    indexes = {
        strategy: defaultdict(int)
        for strategy in {
            strategy
            for strategies in STRATEGIES.values()
            for strategy in strategies
        }
    }

    processed = 0

    for chunk in pd.read_csv(
        source_path,
        sep="\t",
        dtype=str,
        keep_default_na=False,
        usecols=[
            "entity_id",
            "business_name",
            "business_address",
            "country",
        ],
        chunksize=DEFAULT_CHUNK_SIZE,
    ):
        processed += len(chunk)

        for row in chunk.itertuples(index=False):
            keys = generate_blocking_keys(
                row.country,
                row.business_name,
                row.business_address,
            )

            for strategy in indexes:
                key = keys[strategy]

                if key:
                    indexes[strategy][key] += 1

    return indexes


def candidate_count_for_row(row, indexes, strategy_names):
    """
    Estimate number of candidates generated by the union
    of the specified blocking keys.

    Because the same source record may share multiple keys,
    we cannot simply add bucket sizes.

    For this profiling step we use an upper-bound estimate
    by summing bucket sizes.
    """

    keys = generate_blocking_keys(
        row.country,
        row.business_name,
        row.business_address,
    )

    total = 0

    for strategy in strategy_names:
        key = keys[strategy]

        if key:
            total += indexes[strategy].get(key, 0)

    return total


def profile_strategy(sample, indexes, strategy_name, strategy_keys):
    counts = []

    for row in sample.itertuples(index=False):
        count = candidate_count_for_row(
            row,
            indexes,
            strategy_keys,
        )

        counts.append(count)

    counts = np.asarray(counts)

    print("\n" + "=" * 90)
    print(strategy_name)
    print("=" * 90)

    print(f"Sample size:        {len(counts):,}")
    print(f"Mean candidates:    {counts.mean():,.2f}")
    print(f"Median candidates:  {np.percentile(counts, 50):,.0f}")
    print(f"95th percentile:    {np.percentile(counts, 95):,.0f}")
    print(f"99th percentile:    {np.percentile(counts, 99):,.0f}")
    print(f"Maximum:            {counts.max():,.0f}")
    print(
        f"Zero-candidate S1:  "
        f"{(counts == 0).sum():,} "
        f"({(counts == 0).mean():.2%})"
    )

    return counts


def main():

    print("Loading S1 sample...")

    sample = load_s1_sample()

    print(
        f"Sampled {len(sample):,} S1 records"
    )

    print("\nBuilding S2 blocking indexes...")

    s2_indexes = build_candidate_indexes(
        TRAIN_SOURCE2
    )

    print("Building S3 blocking indexes...")

    s3_indexes = build_candidate_indexes(
        TRAIN_SOURCE3
    )

    results = {}

    for strategy_name, strategy_keys in STRATEGIES.items():

        print(
            f"\nProfiling {strategy_name}..."
        )

        # Combine S2 + S3 bucket sizes.
        combined_indexes = {}

        for strategy in strategy_keys:

            combined = defaultdict(int)

            for key, count in s2_indexes[strategy].items():
                combined[key] += count

            for key, count in s3_indexes[strategy].items():
                combined[key] += count

            combined_indexes[strategy] = combined

        counts = profile_strategy(
            sample,
            combined_indexes,
            strategy_name,
            strategy_keys,
        )

        results[strategy_name] = counts

    print("\n" + "=" * 90)
    print("SUMMARY")
    print("=" * 90)

    for strategy_name, counts in results.items():

        print(
            f"{strategy_name:30s} "
            f"median={np.percentile(counts, 50):,.0f}, "
            f"p95={np.percentile(counts, 95):,.0f}, "
            f"p99={np.percentile(counts, 99):,.0f}, "
            f"max={counts.max():,.0f}"
        )


if __name__ == "__main__":
    main()